def get_attempt_prompt(toxic_level: int, attempt_count: int) -> str:
    prefix = f"Это попытка №{attempt_count}. "
    if toxic_level == 1:
        return prefix + "Если ошибка повторяется — поддержи сильнее. Если код стал лучше — отметь это."
    if toxic_level == 2:
        return prefix + "Если ученик повторяет ту же ошибку — подшучивай заметнее."
    return (
        prefix
        + "Если та же ошибка уже была в прошлых попытках — обыграй именно повтор, "
        "каждый раз новым образом. "
        "Если код заметно лучше прошлого — признай это одной фразой, не снижая стиль."
    )


def strip_html(text: str) -> str:
    text = re.sub(r"<[^>]+>", "", text or "")
    return html.unescape(text).strip()


def format_attempts(attempts: list[dict], attempt_count: int) -> str:
    attempts = attempts[-3:]
    first_number = attempt_count - len(attempts) + 1
    parts = []
    for number, attempt in enumerate(attempts, first_number):
        parts.append(f"Попытка №{number}, результат: {attempt['status']}\n{attempt['code']}")
    return "\n\n---\n\n".join(parts)


def format_past_reviews(attempts: list[dict]) -> str:
    # последние два ревью — чтобы модель не повторяла свои же шутки
    reviews = [strip_html(a.get("review") or "") for a in attempts if a.get("review")]
    reviews = [r for r in reviews if r][-2:]
    if not reviews:
        return "нет"
    return "\n\n---\n\n".join(reviews)


_client: AsyncOpenAI | None = None


def get_client() -> AsyncOpenAI:
    # один клиент на процесс: пул соединений и таймаут
    global _client
    if _client is None:
        _client = AsyncOpenAI(
            api_key=OPENROUTER_API_KEY,
            base_url=OPENROUTER_BASE_URL,
            timeout=60,
            max_retries=1,
        )
    return _client


async def ask_gpt(system_prompt: str, user_prompt: str) -> str:
    response = await get_client().chat.completions.create(
        model=GPT_MODEL,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
        max_tokens=REVIEW_MAX_TOKENS,
        temperature=REVIEW_TEMPERATURE,
        # рассуждения нам не нужны: дольше, дороже и съедают лимит токенов
        extra_body={"reasoning": {"effort": "low", "exclude": True}},
    )
    text = response.choices[0].message.content or ""
    return prepare_tg_html(text)


def build_review_prompts(
    code: str,
    condition: str,
    tests_report: str,
    toxic_level: int,
    attempt_count: int,
    recent_attempts: list[dict],
    tests_passed: bool,
) -> tuple[str, str]:
    if toxic_level not in TOXIC_PROMPTS:
        toxic_level = 3

    parts = [
        TOXIC_PROMPTS[toxic_level],
        SECURITY_RULES,
        NO_SOLUTION,
        REVIEW_RULES,
        NOT_CODE_RULE,
        get_attempt_prompt(toxic_level, attempt_count),
    ]
    if toxic_level == 3:
        parts.append(FEW_SHOT_HARD)
    parts.append(TG_FORMAT)
    system_prompt = "\n\n".join(parts)

    if tests_passed:
        shape = ROAST_FORMAT_PASS
    elif toxic_level == 3:
        shape = ROAST_FORMAT_FAIL
    else:
        shape = (
            "Формат ответа:\n"
            "[1–2 предложения в выбранном стиле]\n\n"
            "<b>Что сломалось:</b> [конкретное объяснение причины, без подсказки следующего шага]"
        )

    user_prompt = (
        f"Номер попытки: {attempt_count}\n"
        f"Тесты прошли: {'да' if tests_passed else 'нет'}\n\n"
        f"Задача:\n{condition}\n\n"
        f"Код ученика:\n{code}\n\n"
        f"Результаты тестов:\n{tests_report}\n\n"
        f"Прошлые попытки от старой к новой:\n{format_attempts(recent_attempts, attempt_count)}\n\n"
        f"Прошлые ревью этой задачи (не повторяй их образы):\n{format_past_reviews(recent_attempts)}\n\n"
        f"{shape}\n"
        "На русском. Не пиши решение и не дописывай код."
    )
    return system_prompt, user_prompt


async def review_solution(
    code: str,
    condition: str,
    tests_report: str,
    toxic_level: int,
    attempt_count: int,
    recent_attempts: list[dict],
    tests_passed: bool,
):
    system_prompt, user_prompt = build_review_prompts(
        code, condition, tests_report, toxic_level, attempt_count, recent_attempts, tests_passed
    )
    return await ask_gpt(system_prompt, user_prompt)


