async def _ensure_user(tg_id: int, first_name: str | None):
    user = await get_user(tg_id)
    if user:
        return user
    return await create_user(tg_id, None, first_name)


async def _ensure_block(owner_id: int, viewer_ids: list[int], title: str, tasks: list[dict]):
    personal = await find_set_by_title(owner_id, title)
    if personal is None:
        set_id = await create_set(owner_id, title)
    else:
        set_id = personal["id"]

    for viewer_id in viewer_ids:
        await grant_access(set_id, viewer_id)

    existing = {item["title"]: item for item in await tasks_in_set(set_id)}
    for task in tasks:
        current = existing.get(task["title"])
        if current is None:
            await create_personal_task(
                set_id,
                task["title"],
                task["description"],
                task["tests"],
                2,
            )
            continue
        stored_tests = json.loads(current["tests"])
        if current["description"] == task["description"] and stored_tests == task["tests"]:
            continue
        await update_personal_task(
            set_id,
            current["id"],
            task["title"],
            task["description"],
            task["tests"],
            current["difficulty"],
        )


async def ensure_weekend_sets():
    alex = await _ensure_user(ALEX_TG, "Александр")
    teacher = await _ensure_user(TEACHER_TG, None)
    viewers = [alex["id"], teacher["id"]]
    await _ensure_block(alex["id"], viewers, SATURDAY, SATURDAY_TASKS)
    await _ensure_block(alex["id"], viewers, SUNDAY, SUNDAY_TASKS)
